"""Generate native executable constraints from the sole Python contract source. No dependencies."""
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
from backend.agent.tool_runtime.registry import default_registry

OUTPUT=ROOT/"backend/agent/domain/SkillCatalog/SkillCatalog.generated.inc"
def quote(value): return json.dumps(value,ensure_ascii=True)
def schema(s):
    kind=s["type"]
    if kind=="object":
        fields=",".join("{"+quote(k)+","+schema(v)+"}" for k,v in s["properties"].items())
        return "ParameterSchema::object({"+fields+"},{"+",".join(map(quote,s["required"]))+"})"
    if kind=="array": return "ParameterSchema::array("+schema(s["items"])+","+str(s.get("minItems",0))+","+str(s["maxItems"])+","+str(s.get("uniqueItems",False)).lower()+")"
    if kind=="string": return "ParameterSchema::string("+str(s.get("minLength",0))+","+str(s["maxLength"])+","+quote(s.get("pattern",""))+",{"+",".join(map(quote,s.get("enum",[])))+"})"
    if kind=="integer": return "ParameterSchema::integer("+str(s["minimum"])+","+str(s["maximum"])+")"
    if kind=="boolean": return "ParameterSchema::boolean("+(str(s["const"]).lower() if "const" in s else "std::nullopt")+")"
    raise ValueError("unsupported native schema")
def generate():
    lines=["// Generated by scripts/project/generate_skill_catalog.py; do not hand-edit."]
    aliases={"fleet.get_task_status":"getTaskStatus","fleet.review_failures":"reviewFailures","fleet.propose_sim_reschedule":"proposeSimReschedule"}
    conditions={"authorized_actor":"authorizedActor","human_approval":"humanApproval","confirmed_user_intent":"confirmedUserIntent","atomic_idempotent_port":"atomicIdempotentPort"}
    names=[]
    for n,s in enumerate(default_registry().skills.values()):
        name=aliases.get(s.name,"skill"+str(n)); names.append(name)
        lines += ["static const auto schema"+str(n)+"="+schema(s.parameters)+";",
            "static constexpr std::array pre"+str(n)+"{"+",".join("Precondition::"+conditions[p.value] for p in s.preconditions)+"};",
            "const SkillSpec "+name+"{"+quote(s.name)+","+str(s.version)+",SkillEffect::"+s.effect.value+",",
            'R"json('+json.dumps(s.parameters,separators=(",",":"))+')json",pre'+str(n)+","+quote(s.idempotency_key or "")+","+str(s.timeout_ms)+","+quote(s.description)+",&schema"+str(n)+"};"]
    lines.append("static const SkillSpec generatedSkills[]{"+",".join(names)+"};")
    return "\n".join(lines)+"\n"
if __name__=="__main__":
    content=generate()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="utf-8")!=content: raise SystemExit("native skill catalog is stale")
        print("native catalog matches executable Python contracts")
    else:
        OUTPUT.write_text(content,encoding="utf-8"); print("generated",OUTPUT.relative_to(ROOT))
