BEGIN;

CREATE TABLE file_objects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_name VARCHAR(255) NOT NULL,
    media_type VARCHAR(127) NOT NULL,
    expected_size BIGINT NOT NULL CHECK (expected_size BETWEEN 1 AND 26214400),
    uploaded_size BIGINT NOT NULL DEFAULT 0
        CHECK (uploaded_size >= 0 AND uploaded_size <= expected_size),
    sha256 CHAR(64) NOT NULL DEFAULT '',
    state VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending', 'ready', 'failed', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL,
    ready_at TIMESTAMPTZ,
    CHECK ((state = 'ready' AND uploaded_size = expected_size AND length(sha256) = 64
            AND ready_at IS NOT NULL)
        OR (state <> 'ready'))
);

ALTER TABLE users
    ADD COLUMN avatar_file_id BIGINT REFERENCES file_objects(id) ON DELETE SET NULL;

CREATE TABLE message_attachments (
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES file_objects(id) ON DELETE RESTRICT,
    position SMALLINT NOT NULL DEFAULT 0 CHECK (position BETWEEN 0 AND 7),
    PRIMARY KEY (message_id, file_id),
    UNIQUE (message_id, position)
);

CREATE INDEX idx_file_objects_owner_created
    ON file_objects(owner_id, created_at DESC);
CREATE INDEX idx_message_attachments_file
    ON message_attachments(file_id);

INSERT INTO phase11_schema_migrations(version, description)
VALUES (5, 'file metadata, message attachments and user avatars')
ON CONFLICT (version) DO NOTHING;

COMMIT;
