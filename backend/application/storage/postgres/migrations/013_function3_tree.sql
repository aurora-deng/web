BEGIN;
-- 新模块只增加表。账号、附件和会话事实继续由旧模块拥有。
CREATE TABLE site_roles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id),
 role TEXT NOT NULL CHECK(role IN ('user','moderator','administrator'))
);
CREATE TABLE tree_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(40) NOT NULL UNIQUE,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
INSERT INTO tree_categories(name) VALUES ('生活'),('学习'),('心情'),('技术'),('旅行'),('心愿');
CREATE TABLE tree_posts (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id),
 request_key VARCHAR(128) NOT NULL,
 canonical_request TEXT NOT NULL,
 body TEXT NOT NULL CHECK(char_length(body)<=2000),
 category_id BIGINT NOT NULL REFERENCES tree_categories(id),
 mood VARCHAR(64) NOT NULL DEFAULT '',
 state TEXT NOT NULL DEFAULT 'published' CHECK(state IN ('published','hidden','deleted')),
 created_ms BIGINT NOT NULL,
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 UNIQUE(author_id,request_key)
);
CREATE INDEX tree_posts_visible_idx ON tree_posts(id DESC) WHERE state='published';
CREATE INDEX tree_posts_category_idx ON tree_posts(category_id,id DESC) WHERE state='published';
CREATE INDEX tree_posts_rank_idx ON tree_posts(created_ms,id) WHERE state='published';
CREATE TABLE tree_tags (
 post_id BIGINT REFERENCES tree_posts(id), tag VARCHAR(64) NOT NULL, PRIMARY KEY(post_id,tag)
);
CREATE INDEX tree_tags_search_idx ON tree_tags(tag,post_id);
-- 只记录经独立媒体处理任务验证的文件，浏览器声明的 MIME/时长不可信。
CREATE TABLE tree_media_validation (
 file_id BIGINT PRIMARY KEY REFERENCES file_objects(id),
 kind TEXT NOT NULL CHECK(kind IN ('image','audio')),
 bytes BIGINT NOT NULL CHECK(bytes>0),
 duration_ms BIGINT NOT NULL DEFAULT 0,
 validator TEXT NOT NULL, validated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tree_media (
 post_id BIGINT REFERENCES tree_posts(id), file_id BIGINT REFERENCES tree_media_validation(file_id),
 position SMALLINT NOT NULL CHECK(position BETWEEN 0 AND 6), PRIMARY KEY(post_id,file_id), UNIQUE(post_id,position)
);
CREATE TABLE tree_likes (
 post_id BIGINT REFERENCES tree_posts(id), user_id BIGINT REFERENCES users(id), PRIMARY KEY(post_id,user_id)
);
CREATE TABLE tree_replies (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES tree_posts(id), author_id BIGINT NOT NULL REFERENCES users(id),
 request_key VARCHAR(128) NOT NULL, body TEXT NOT NULL CHECK(char_length(body) BETWEEN 1 AND 1000),
 created_ms BIGINT NOT NULL, deleted BOOLEAN NOT NULL DEFAULT FALSE, UNIQUE(author_id,request_key)
);
CREATE INDEX tree_replies_page_idx ON tree_replies(post_id,id DESC) WHERE NOT deleted;
CREATE INDEX tree_replies_rank_idx ON tree_replies(post_id,author_id) WHERE NOT deleted;
CREATE TABLE function3_outbox (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, event_type TEXT NOT NULL,
 aggregate_type TEXT NOT NULL, aggregate_id BIGINT NOT NULL, aggregate_version BIGINT NOT NULL,
 payload JSONB NOT NULL, created_ms BIGINT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','inflight','published','dead')),
 attempts INTEGER NOT NULL DEFAULT 0, available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 lease_until TIMESTAMPTZ, last_error TEXT NOT NULL DEFAULT '',
 UNIQUE(event_type,aggregate_type,aggregate_id,aggregate_version)
);
CREATE INDEX function3_outbox_due_idx ON function3_outbox(state,available_at,id);
CREATE TABLE function3_inbox (
 consumer TEXT NOT NULL, event_id BIGINT NOT NULL, processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(consumer,event_id)
);
CREATE TABLE site_audit (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL, resource TEXT NOT NULL, reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE content_reports (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES tree_posts(id),
 reporter_id BIGINT NOT NULL REFERENCES users(id), reason TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','resolved','dismissed')),
 UNIQUE(post_id,reporter_id)
);
CREATE TABLE tree_rank_versions (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 settled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, slot BIGINT NOT NULL UNIQUE
);
CREATE TABLE tree_rank_entries (
 version_id BIGINT REFERENCES tree_rank_versions(id), rank SMALLINT NOT NULL CHECK(rank BETWEEN 1 AND 10),
 post_id BIGINT NOT NULL REFERENCES tree_posts(id), score DOUBLE PRECISION NOT NULL,
 PRIMARY KEY(version_id,rank), UNIQUE(version_id,post_id)
);
CREATE TABLE announcements (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, rank_version BIGINT NOT NULL UNIQUE REFERENCES tree_rank_versions(id),
 text TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP + INTERVAL '5 minutes'
);
CREATE TABLE announcement_audio (
 announcement_id BIGINT REFERENCES announcements(id), voice TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','ready','failed')),
 cache_key TEXT NOT NULL DEFAULT '', attempts INTEGER NOT NULL DEFAULT 0, last_error TEXT NOT NULL DEFAULT '',
 PRIMARY KEY(announcement_id,voice)
);
CREATE TABLE notification_settings (
 user_id BIGINT PRIMARY KEY REFERENCES users(id), announcement_sound BOOLEAN NOT NULL DEFAULT FALSE,
 voice TEXT NOT NULL DEFAULT 'zf_001' CHECK(voice IN ('zf_001','zm_009'))
);
